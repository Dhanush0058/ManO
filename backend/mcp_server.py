import os
import json
from mcp.server.fastmcp import FastMCP

# Initialize the MCP Server
mcp = FastMCP("ManO Local Tools")

# Ensure a local directory exists for file operations
WORK_DIR = os.path.join(os.path.dirname(__file__), "agent_work")
os.makedirs(WORK_DIR, exist_ok=True)

@mcp.tool()
def calculate_burn_rate(cash: float, monthly_expenses: float) -> str:
    """Calculates runway in months given total cash and monthly expenses."""
    if monthly_expenses <= 0:
        return "Infinite runway (expenses are zero or negative)."
    runway = cash / monthly_expenses
    return f"Calculated runway: {runway:.1f} months based on ${cash:,.2f} cash and ${monthly_expenses:,.2f} monthly burn."

@mcp.tool()
def generate_nda(company_name: str) -> str:
    """Generates a standard NDA draft and saves it to the local workspace."""
    nda_content = f"NON-DISCLOSURE AGREEMENT\n\nThis agreement is between ManO and {company_name}...\n\n(Generated by Legal Agent)"
    file_path = os.path.join(WORK_DIR, f"NDA_{company_name.replace(' ', '_')}.txt")
    with open(file_path, "w") as f:
        f.write(nda_content)
    return f"Drafted NDA and saved to {file_path}"

@mcp.tool()
def save_lead(name: str, email: str, company: str) -> str:
    """Saves a sales lead to a local CRM JSON file."""
    crm_file = os.path.join(WORK_DIR, "crm_leads.json")
    leads = []
    if os.path.exists(crm_file):
        with open(crm_file, "r") as f:
            leads = json.load(f)
    
    leads.append({"name": name, "email": email, "company": company})
    
    with open(crm_file, "w") as f:
        json.dump(leads, f, indent=2)
        
    return f"Successfully saved lead {name} from {company} to CRM."

@mcp.tool()
def screen_resume(candidate_name: str) -> str:
    """Simulates screening a resume for a candidate."""
    return f"Screened resume for {candidate_name}. Candidate matches 85% of requirements for a typical software engineer role. Recommended for interview."

if __name__ == "__main__":
    # When run directly, start the FastMCP stdio server
    mcp.run()
