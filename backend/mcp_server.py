@mcp.tool()
def send_email(to_email: str, subject: str, body: str, sender: str = "dhanushreddy52006@gmail.com") -> str:
    """
    MCP Email Delivery Tool.
    Sends real emails via live SMTP (if configured in .env) or archives via MCP email layer.
    """
    mailbox_file = os.path.join(WORK_DIR, "sent_emails.json")
    emails = []
    if os.path.exists(mailbox_file):
        with open(mailbox_file, "r", encoding="utf-8") as f:
            try:
                emails = json.load(f)
            except Exception:
                emails = []

    # Check for live SMTP credentials in .env
    smtp_host = os.getenv("SMTP_HOST", "smtp.gmail.com")
    smtp_port = int(os.getenv("SMTP_PORT", "587"))
    smtp_user = os.getenv("SMTP_USER", "").strip()
    smtp_password = os.getenv("SMTP_PASSWORD", "").replace(" ", "").strip()
    smtp_from = os.getenv("SMTP_FROM", "dhanushreddy52006@gmail.com").strip() or "dhanushreddy52006@gmail.com"

    real_send_status = "Archived to local MCP mailbox"
    
    if smtp_user and smtp_password:
        try:
            msg = MIMEMultipart()
            msg["From"] = f"{smtp_from}"
            msg["To"] = to_email
            msg["Subject"] = subject
            msg.attach(MIMEText(body, "plain"))

            with smtplib.SMTP(smtp_host, smtp_port, timeout=15) as server:
                server.starttls()
                server.login(smtp_user, smtp_password)
                server.send_message(msg)
            real_send_status = f"Dispatched live via SMTP server ({smtp_host}) to {to_email}"
        except Exception as e:
            real_send_status = f"SMTP live dispatch failed ({str(e)}), saved to local mailbox"

    email_record = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "sender": smtp_from,
        "to_email": to_email,
        "subject": subject,
        "body": body,
        "status": real_send_status,
        "protocol": "SMTP / MCP Protocol"
    }
    emails.append(email_record)

    with open(mailbox_file, "w", encoding="utf-8") as f:
        json.dump(emails, f, indent=2)

    return (
        f"✅ [MCP Email Delivery]\n"
        f"Sender: {smtp_from}\n"
        f"Recipient: {to_email}\n"
        f"Subject: {subject}\n"
        f"Delivery Status: {real_send_status}\n"
        f"Archive: {mailbox_file}"
    )


@mcp.tool()
def lookup_contact(query: str) -> str:
    """Look up a contact through the configured application database."""
    session = SessionLocal()
    try:
        entity = EntityLookupAdapter.identify_entity_by_email_or_name(session, query)
        if entity.get("found"):
            return (
                f"Found {entity['name']} ({entity.get('match_type', 'Contact')}) "
                f"at {entity['email']}."
            )
        return f"No registered contact found for '{query}'."
    finally:
        session.close()


